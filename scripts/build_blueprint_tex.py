#!/usr/bin/env python3
"""Generate the data-driven LaTeX of the illustrated blueprint (``blueprint/atlas-blueprint.tex``).

    python3 -B scripts/build_blueprint_tex.py            # writes blueprint/generated/*
    python3 -B scripts/build_blueprint_tex.py --epoch    # prints SOURCE_DATE_EPOCH (status time)
    python3 -B scripts/build_blueprint_tex.py --figures  # prints the SVG names the PDF uses

Inputs (never edited here): ``data/model.json`` (components, interfaces, cuts, 87 nodes, tiers,
status, pins, timeline), ``data/announcement_dates.json``, ``data/source/sources.json`` (module
count), ``data/source/PROVENANCE.json``, ``assets/figures/*.svg`` (titles and descriptions become
captions), ``verification/logs/axioms.json`` and the Lean files in ``lean/`` and
``references/archive-bridges/`` (quoted verbatim, line by line, with syntax colouring added).

Outputs (deterministic; one file per part of the document) in ``blueprint/generated/``:
``macros.tex`` (colours, tier and stratum data, pins, status, counts), ``legend.tex`` (tiers,
strata, itineraries), ``diagram.tex`` (the TikZ picture of the whole proof), ``components.tex``
(one section per stratum, one subsection per component), ``cuts.tex``, ``skeleton.tex`` and
``axioms.tex`` (Lean quotations and the axiom report), ``nodes.tex`` (the 87-declaration table),
``timeline.tex`` and ``pins.tex``; ``--figures`` gives the figure list to the Makefile.

The mathematics is not rewritten: LaTeX statements are kept, Markdown is converted (``$...$``
stays math, backticks become linked code), and plain-text fields only get typographic treatment
(Lean identifiers in monospace, ``x^(...)``-style exponents as math, Greek letters as math).
"""
