def gen_pins() -> None:
    pins, st = MODEL["pins"], MODEL["status"]
    iw = st["independent_window"]
    mirror = pins["mirror"] + "/tree/" + pins["mirror_commit"]
    mathlib = "https://github.com/leanprover-community/mathlib4/tree/" + pins["mathlib"]
    rows = [
        ("Announcement PDF (SHA-256)", r"\bphash{%s}" % pins["pdf_sha256"]),
        ("Lean archive (SHA-256 of the gzip stream, %d parts)" % len(SOURCES["parts"]), r"\bphash{%s}" % pins["archive_sha256"]),
        ("Lean files in the archive", fmt_int(SOURCES["lean_files"])),
        ("Archive toolchain", r"\bpcode{%s}" % code_inner(pins["toolchain"])),
        ("Mathlib commit", r"\href{%s}{\bphash{%s}}" % (url_tex(mathlib), pins["mathlib"])),
        ("Public mirror (all source links)", r"\href{%s}{\bpcode{%s}} at \bphash{%s}" % (url_tex(mirror), code_inner(pins["mirror"].split("github.com/")[-1]), pins["mirror_commit"])),
        ("Reading project commit imported", r"\bphash{%s}" % PROV["source_commit"]),
        ("Import time", esc(PROV["imported_utc"].replace("T", " ").replace("+00:00", " UTC"))),
        ("Status record as of", esc(st["as_of"][:19].replace("T", " ") + " UTC") + r", Helios job \bpcode{%s}" % esc(st["job"])),
        ("Prime-window proof export", r"%s declarations; %s bytes compressed (SHA-256 \bphash{%s})" % (
            fmt_int(iw["declarations"]), fmt_int(iw["compressed_bytes"]), iw["compressed_sha256"])),
    ]
    L = [r"\begin{bppintable}"]
    for k, v in rows:
        L.append(r"\bppinrow{%s}{%s}" % (esc(k), v))
    L.append(r"\end{bppintable}")
    write("pins.tex", "\n".join(L))
    L = [r"\begin{bpsourcelist}"]
    for s in st["external_sources"]:
        L.append(r"\item \href{%s}{%s}" % (url_tex(s["url"]), esc(s["label"])))
    L.append(r"\end{bpsourcelist}")
    write("external.tex", "\n".join(L))
    L = [r"\begin{bpprovenance}"]
    for f in PROV["files"]:
        L.append(r"\bpprovrow{%s}{%s}{%s}" % (code(f["to"]), code(f["from"]), f["sha256"][:16]))
    L.append(r"\end{bpprovenance}")
    write("provenance.tex", "\n".join(L))


# ----------------------------------------------------------------------------- main
def figures_used() -> list[str]:
    names = {c["figure"] for c in MODEL["components"] if c.get("figure")}
    names |= {"hero", "blueprint-graph"}
    return sorted(names)


def main(argv: list[str]) -> int:
    if "--epoch" in argv:
        print(int(as_of().timestamp()))
        return 0
    if "--figures" in argv:
        print(" ".join(figures_used()))
        return 0
    build_index()
    gen_macros()
    gen_legend()
    gen_diagram()
    gen_components()
    gen_cuts()
    gen_skeleton()
    gen_nodes()
    gen_timeline()
    gen_pins()
    for w in WARNINGS:
        print("warning:", w, file=sys.stderr)
    files = sorted(p.name for p in OUT.iterdir())
    print(f"blueprint: {len(files)} generated files in {OUT.relative_to(ROOT)}; "
          f"{len(MODEL['components'])} components, {len(MODEL['nodes'])} nodes, {len(FIG_SHOWN)} figures")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
