def gen_macros() -> None:
    st, pins = MODEL["status"], MODEL["pins"]
    t = as_of()
    L = []
    for s in MODEL["strata"]:
        L.append(r"\definecolor{stratum-%s}{HTML}{%s}" % (s["id"], s["color"].lstrip("#").upper()))
        L.append(r"\expandafter\def\csname bp@strattitle@%s\endcsname{%s}" % (s["id"], esc(s["title"])))
    for k, v in TIERS.items():
        L.append(r"\definecolor{tier-%s}{HTML}{%s}" % (k, v["color"].lstrip("#").upper()))
        L.append(r"\expandafter\def\csname bp@tierlabel@%s\endcsname{%s}" % (k, esc(v["label"])))
        L.append(r"\expandafter\def\csname bp@tiericon@%s\endcsname{%s}" % (k, v["icon"]))
    for n in MODEL["nodes"]:
        L.append(r"\expandafter\def\csname bp@nodetitle@%s\endcsname{%s}" % (n["id"], ptex(n["title"], link=False)))
        L.append(r"\expandafter\def\csname bp@nodetier@%s\endcsname{%s}" % (n["id"], n["tier"]))
