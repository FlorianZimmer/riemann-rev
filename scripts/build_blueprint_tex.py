def gen_nodes() -> None:
    L = [r"\begin{bpnodetable}"]
    for c in READING:
        L.append(r"\bpnodegroup{%s}{%s}{%d}{%s}{%d}" % (c["id"], c["stratum"], c["n"], ptex(c["title"], link=False), len(c["nodes"])))
        for nid in c["nodes"]:
            n = NODE[nid]
            if n["declaration"]:
                decl = code(n["declaration"], n["url"])
                loc = esc(src_location(n["url"]))
            else:
                decl = r"\bpnodecl"
                loc = ""
            L.append(r"\bpnoderow{%s}{%s}{%s}{%s}{%s}{%s}" % (nid, n["tier"], ptex(n["title"], link=False), decl, loc,
                                                           ptex(n["contract"], link=False)))
    L.append(r"\end{bpnodetable}")
    write("nodes.tex", "\n".join(L))
    # the static graph in two halves (cut between node columns 7 and 8)
    w, h = svg_size("blueprint-graph")
    title, desc = svg_meta("blueprint-graph")
    root = (ROOT / "assets" / "figures" / "blueprint-graph.svg").read_text(encoding="utf-8")
    xs = sorted({float(a) for a in re.findall(r'<g transform="translate\(([\d.]+),[\d.]+\)"><rect width="212"', root)})
    ys = sorted({float(b) for b in re.findall(r'<g transform="translate\([\d.]+,([\d.]+)\)"><rect width="212"', root)})
    off = [float(v) for v in re.search(r'<g transform="translate\(([\d.]+),([\d.]+)\)">', root).groups()]
    mid = len(xs) // 2
    split_px = off[0] + (xs[mid - 1] + 212 + xs[mid]) / 2
    top_px = off[1] + ys[0] - 10
    bot_px = off[1] + ys[-1] + 46 + 10
    k = 0.75   # rsvg-convert: 1 px = 0.75 bp
    left, right = split_px, w - split_px
    big = max(left, right)
    # both halves at one scale, as wide as the landscape text block (277 mm) allows when the two
    # halves plus rule and caption (about 16 mm) must fit into its height (190 mm)
    half_h = 277.0 * (bot_px - top_px) / big
    fit = min(1.0, (190.0 - 16.0) / (2 * half_h))
    write("graph.tex", r"\bpgraph{%.2f}{%.2f}{%.2f}{%.2f}{%.4f}{%.4f}{%s}{%s}" % (
        right * k, left * k, top_px * k, (h - bot_px) * k, fit * left / big, fit * right / big,
        caption_text(title), caption_text(desc)))


