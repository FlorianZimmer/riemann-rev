# ----------------------------------------------------------------------------- Lean quotation
LEAN_KW = {"theorem", "lemma", "def", "structure", "where", "fun", "by", "have", "show", "from",
           "match", "with", "example", "namespace", "end", "variable", "inductive", "instance", "class",
           "let", "in", "if", "then", "else", "import", "open", "noncomputable", "section", "abbrev",
           "calc", "at", "using", "only", "deriving", "extends", "mutual", "set_option", "private",
           "protected"}
LEAN_TAC = {"intro", "exact", "obtain", "rcases", "refine", "rw", "subst", "change", "generalize",
            "omega", "decide", "simp", "simpa", "apply", "rfl", "constructor", "cases", "induction",
            "norm_num", "exists_between", "rwa", "classical", "funext", "linarith", "positivity"}
LEAN_SORT = {"Prop", "Type", "Sort"}
DECL_RE = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:noncomputable\s+|private\s+|protected\s+)*"
                     r"(theorem|lemma|def|structure|abbrev|inductive|class|instance)\s+([^\s:({\[]+)")


def lean_blocks(path: Path) -> dict[str, tuple[int, int]]:
    """Top-level declarations -> (first line incl. doc comment, last line), 1-based."""
    lines = path.read_text(encoding="utf-8").split("\n")
    starts = []
    for i, ln in enumerate(lines):
        m = DECL_RE.match(ln)
        if m:
            starts.append((i, m.group(2)))
    blocks = {}
    for k, (i, name) in enumerate(starts):
        first = i
        j = i - 1
        if j >= 0 and lines[j].rstrip().endswith("-/"):
            while j >= 0 and not lines[j].lstrip().startswith("/-"):
                j -= 1
            if j >= 0:
                first = j
        last = i
        stop = len(lines)
        for t in range(i + 1, len(lines)):
            ln = lines[t]
            if ln and not ln[0].isspace() and (DECL_RE.match(ln) or ln.startswith(("/-", "end ", "#", "namespace", "variable", "--", "example", "theorem", "def "))):
                stop = t
                break
        last = stop - 1
        while last > i and not lines[last].strip():
            last -= 1
        blocks[name] = (first + 1, last + 1)
    return blocks


def lean_highlight(text: str) -> list[str]:
    """Colour Lean source for fancyvrb (commandchars=\\\\\\{\\}); returns one string per line."""
    out_lines: list[list[str]] = [[]]

    def emit(cmd: str | None, s: str) -> None:
        pieces = s.split("\n")
        for k, p in enumerate(pieces):
            if k:
                out_lines.append([])
            if p:
                body = "".join({"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}"}.get(c, c) for c in p)
                out_lines[-1].append(r"\%s{%s}" % (cmd, body) if cmd else body)

    i, n = 0, len(text)
    prev_decl_kw = False
    while i < n:
        if text.startswith("/-", i):
            depth, j = 0, i
            while j < n:
                if text.startswith("/-", j):
                    depth += 1
                    j += 2
                elif text.startswith("-/", j):
                    depth -= 1
                    j += 2
                    if depth == 0:
                        break
                else:
                    j += 1
            emit("LCom", text[i:j])
            i = j
            continue
        if text.startswith("--", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            emit("LCom", text[i:j])
            i = j
            continue
        if text[i] == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            emit("LStr", text[i:j + 1])
            i = j + 1
            continue
        if text[i] == "#" and i + 1 < n and text[i + 1].isalpha():
            m = re.match(r"#[A-Za-z_]+", text[i:])
            emit("LKw", m.group(0))
            i += m.end()
            continue
        m = re.match(r"[A-Za-z_][\w'.₀-₉!?]*", text[i:])
        if m and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] in "_.'")):
            tok = m.group(0)
            if prev_decl_kw:
                emit("LDecl", tok)
                prev_decl_kw = False
            elif tok in LEAN_KW:
                emit("LKw", tok)
                prev_decl_kw = tok in {"theorem", "lemma", "def", "structure", "abbrev", "inductive", "class"}
            elif tok in LEAN_TAC:
                emit("LTac", tok)
            elif tok in LEAN_SORT:
                emit("LSort", tok)
            else:
                emit(None, tok)
            i += m.end()
            continue
        emit(None, text[i])
        if not text[i].isspace():
            prev_decl_kw = False
        i += 1
    return ["".join(x) for x in out_lines]


def lean_quote(rel: str, names: list[str]) -> tuple[str, list[tuple[str, int, int]]]:
    """Verbatim quotation of the named declarations (contiguous runs merged), coloured."""
    path = ROOT / rel
    lines = path.read_text(encoding="utf-8").split("\n")
    blocks = lean_blocks(path)
    spans = []
    for nm in names:
        if nm not in blocks:
            raise SystemExit(f"declaration {nm} not found in {rel}")
        spans.append((nm,) + blocks[nm])
    spans.sort(key=lambda t: t[1])
    groups: list[list] = []
    for nm, a, b in spans:
        if groups and a <= groups[-1][2] + 2:
            groups[-1][2] = max(groups[-1][2], b)
            groups[-1][0].append(nm)
        else:
            groups.append([[nm], a, b])
    out = []
    for nms, a, b in groups:
        body = "\n".join(lines[a - 1:b])
        hl = lean_highlight(body)
        out.append(r"\begin{bpleanquote}{%s}{%d}{%d}" % (esc(rel), a, b))
        out.append(r"\begin{bplean}[firstnumber=%d]" % a)
        out.extend(hl)
        out.append(r"\end{bplean}")
        out.append(r"\end{bpleanquote}")
    return "\n".join(out), spans


