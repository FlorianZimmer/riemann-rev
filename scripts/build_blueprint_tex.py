def gen_timeline() -> None:
    tl = {t["number"]: t for t in MODEL["timeline"]}
    dd = {d["number"]: d for d in DATES["items"]}
    assert set(tl) == set(dd), "timeline and dates disagree"
    days = sorted({date.fromisoformat(d["date"]) for d in DATES["items"]})
    ann = as_of().date()
    # broken axis: one segment per month present
    months = sorted({(d.year, d.month) for d in days + [ann]})
    segs = []
    for (yy, mm) in months:
        md_ = [d for d in days + [ann] if (d.year, d.month) == (yy, mm)]
        segs.append((min(md_), max(md_)))
    unit = 6.2   # mm per day
    pad = 4.0
    x = 0.0
    seg_x = []
    for a, b in segs:
        seg_x.append((x, a, b))
        x += (b - a).days * unit + 2 * pad + 9.0
    total = x - 9.0
    scale = min(1.0, 160.0 / total)

    def xpos(d: date) -> float:
        for x0, a, b in seg_x:
            if a <= d <= b:
                return (x0 + pad + (d - a).days * unit) * scale
        raise ValueError(d)

    P = [r"\begin{tikzpicture}[x=1mm,y=1mm,bptimeline]"]
    for x0, a, b in seg_x:
        xa, xb = x0 * scale, (x0 + 2 * pad + (b - a).days * unit) * scale
        P.append(r"\draw[bptlaxis] (%.2f,0) -- (%.2f,0);" % (xa, xb))
        P.append(r"\node[bptlmonth] at (%.2f,-6.2) {%s %d};" % ((xa + xb) / 2, a.strftime("%B"), a.year))
    for i in range(len(seg_x) - 1):
        xb = (seg_x[i][0] + 2 * pad + (seg_x[i][2] - seg_x[i][1]).days * unit) * scale
        xa = seg_x[i + 1][0] * scale
        P.append(r"\node[bptlbreak] at (%.2f,0) {};" % ((xa + xb) / 2))
    for d in days:
        P.append(r"\draw[bptltick] (%.2f,0) -- ++(0,-1.2) node[below,bptlday] {%d};" % (xpos(d), d.day))
    P.append(r"\draw[bptlann] (%.2f,-1.2) -- (%.2f,44) node[above,bptlannlabel] {announcement};" % (xpos(ann), xpos(ann)))
    P.append(r"\node[below,bptlday] at (%.2f,-1.2) {%d};" % (xpos(ann), ann.day))
    stack: dict[date, int] = {}
    for num in sorted(dd):
        d = date.fromisoformat(dd[num]["date"])
        k = stack.get(d, 0)
        stack[d] = k + 1
        comp = tl[num]["component"]
        col = ("stratum-" + COMP[comp]["stratum"]) if comp else "tier-motivation"
        yy = 3.6 + 4.6 * k
        P.append(r"\node[bptldot=%s] (tl%d) at (%.2f,%.2f) {\hyperlink{tl:%d}{%d}};" % (col, num, xpos(d), yy, num, num))
        if dd[num]["from_on"]:
            P.append(r"\draw[bptlfrom=%s] (tl%d.east) -- ++(3.2,0);" % (col, num))
    P.append(r"\end{tikzpicture}")
    write("timeline-picture.tex", "\n".join(P))
    L = [r"\begin{bptimelinetable}"]
    for num in sorted(tl):
        t, d = tl[num], dd[num]
        comp = t["component"]
        cref = r"\bpcompref{%s}" % comp if comp else r"\bpnocomp"
        dt = date.fromisoformat(d["date"])
        L.append(r"\bptlrow{%d}{%s}{%s}{%s}{%d}{%s}{%s}{%s}{%s}" % (
            num, esc(d["as_written"]), long_date(dt) + (" onwards" if d["from_on"] else ""), ptex(t["topic"]),
            t["page"], ptex(t["relation"]), cref, ptex(t["assessment"]), ("stratum-" + COMP[comp]["stratum"]) if comp else "tier-motivation"))
    L.append(r"\end{bptimelinetable}")
    write("timeline.tex", "\n".join(L))


