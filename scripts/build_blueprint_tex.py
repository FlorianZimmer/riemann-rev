# ----------------------------------------------------------------------------- text conversion
SPECIAL = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$", "&": r"\&", "#": r"\#",
           "%": r"\%", "_": r"\_", "^": r"\textasciicircum{}", "~": r"\textasciitilde{}"}
GREEK = set("αβγδεζηθικλμνξπρστυφχψωΓΔΘΛΞΠΣΦΨΩ")
NOT_IDENT = {"NanoDA", "GitHub", "LaTeX", "TeX"}
KNOWN_IDENT = {"propext"}   # lowercase Lean names that the patterns below cannot recognise


def esc(s: str) -> str:
    return "".join(SPECIAL.get(c, c) for c in s)


def url_tex(u: str) -> str:
    """A URL for the first argument of \\href inside other macros' arguments."""
    return u.replace("\\", "/").replace("#", r"\#").replace("%", r"\%")


def code_inner(s: str) -> str:
    out = []
    for c in s:
        if c == ".":
            out.append(r".\allowbreak{}")
        elif c == "_":
            out.append(r"\_\allowbreak{}")
        elif c == "/":
            out.append(r"/\allowbreak{}")
        else:
            out.append(SPECIAL.get(c, c))
    return "".join(out)


def code(s: str, url: str | None = None) -> str:
    """A Lean identifier in monospace, breakable after . _ /, optionally linked."""
    body = r"\bpcode{%s}" % code_inner(s)
    return r"\href{%s}{%s}" % (url_tex(url), body) if url else body


class Quotes:
    """Alternating curly double quotes for straight ones."""

    def __init__(self) -> None:
        self.open = False

    def __call__(self) -> str:
        self.open = not self.open
        return "“" if self.open else "”"


def take_group(t: str, j: int) -> tuple[str, int]:
    """After '^': a balanced (...) or {...} group (without its delimiters), or one token."""
    if j >= len(t):
        return "", j
    if t[j] in "({":
        close = ")" if t[j] == "(" else "}"
        depth, k = 0, j
        while k < len(t):
            if t[k] == t[j]:
                depth += 1
            elif t[k] == close:
                depth -= 1
                if depth == 0:
                    return t[j + 1:k], k + 1
            k += 1
        return t[j + 1:], len(t)
    m = re.match(r"[A-Za-z0-9]+|−?[^\s,;.)]", t[j:])
    if m:
        return m.group(0), j + m.end()
    return "", j


def mathify(s: str) -> str:
    s = s.replace("½", "1/2").replace("·", r"\cdot ").replace("%", r"\%").replace("#", r"\#")
    s = re.sub(r"\bsqrt\(([^()]*)\)", r"\\sqrt{\1}", s)
    s = re.sub(r"\bexp\b", r"\\exp", s)
    s = re.sub(r"\blog\b", r"\\log", s)
    return s


def textmath(t: str, q: Quotes | None = None) -> str:
    """Plain prose with pseudo-math: base_x, base^(...), sqrt(...), √x, Greek letters."""
    q = q or Quotes()
    out: list[str] = []
    i = 0
    while i < len(t):
        prev_alnum = i > 0 and (t[i - 1].isalnum() or t[i - 1] in "_")
        if not prev_alnum:
            m = re.match(r"([A-Za-z]{1,2})_([A-Za-z0-9])(?![\w])", t[i:])
            if m:
                base, sub = m.groups()
                b = r"\mathrm{%s}" % base if len(base) == 2 else base
                out.append(r"\(%s_{%s}\)" % (b, sub))
                i += m.end()
                continue
            m = re.match(r"([A-Za-z]+)_\{([^{}]*)\}", t[i:])
            if m:
                word, sub = m.groups()
                head = r"\sum" if word == "sum" else r"\mathrm{%s}" % word
                out.append(r"\(%s_{%s}\)" % (head, mathify(sub)))
                i += m.end()
                continue
            m = re.match(r"([A-Za-z0-9]+)\^", t[i:])
            if m:
                sup, j = take_group(t, i + m.end())
                out.append(r"\(%s^{%s}\)" % (mathify(m.group(1)), mathify(sup)))
                i = j
                continue
            if t.startswith("sqrt(", i):
                inner, j = take_group(t, i + 4)
                out.append(r"\(\sqrt{%s}\)" % mathify(inner))
                i = j
                continue
        if t[i] == "^":                       # after ')' or ']'
            sup, j = take_group(t, i + 1)
            out.append(r"\(^{%s}\)" % mathify(sup))
            i = j
            continue
        if t.startswith(")_+", i):
            out.append(r")\(_{+}\)")
            i += 3
            continue
        if t[i] == "√":
            m = re.match(r"√([A-Za-z0-9]+|\([^()]*\))", t[i:])
            if m:
                arg = m.group(1)
                arg = arg[1:-1] if arg.startswith("(") else arg
                out.append(r"\(\sqrt{%s}\)" % mathify(arg))
                i += m.end()
                continue
        c = t[i]
        if c in GREEK:
            out.append(r"\(%s\)" % c)
        elif c == '"':
            out.append(q())
        else:
            out.append(SPECIAL.get(c, c))
        i += 1
    return "".join(out)


IDENT_RE = re.compile(r"""
 (?<![\w.\\$])
 (
   KNOWN
 | [A-Za-z][\w'₀-₉]*(?:\.[A-Za-z_][\w'₀-₉]*)+
 | [A-Za-z][\w'₀-₉]*_[\w'₀-₉]+
 | [a-z][a-z0-9]*[A-Z][\w'₀-₉]*
 | [A-Z][a-z0-9]+[A-Z][\w'₀-₉]*
 | [A-Z]{2,}[a-z]+[\w'₀-₉]*
 | [A-Z][a-z]+[0-9]+[a-z]*
 | [a-z]{3,}[0-9]+
 )
 (?![\w])
""".replace("KNOWN", "|".join(sorted(KNOWN_IDENT))), re.X)


def is_ident(tok: str) -> bool:
    if tok in NOT_IDENT or re.fullmatch(r"[a-z]\.[a-z]", tok):
        return False
    if re.fullmatch(r"[A-Za-z]{1,2}_[A-Za-z0-9]", tok):      # e_D, G_P, GL_a: math
        return False
    if re.fullmatch(r"[A-Z][a-z]+'s", tok):
        return False
    return True


def ptex(s: str, link: bool = True, comp: str | None = None) -> str:
    """Plain-text field: $...$ kept as math, Lean identifiers in (linked) monospace, the rest via
    textmath."""
    if "$" in s:
        return "".join(p if p.startswith("$") and p.endswith("$") and len(p) > 1 else ptex(p, link, comp)
                       for p in re.split(r"(\$[^$]+\$)", s) if p)
    q = Quotes()
    out, pos = [], 0
    for m in IDENT_RE.finditer(s):
        tok = m.group(1)
        if not is_ident(tok):
            continue
        out.append(textmath(s[pos:m.start()], q))
        out.append(code(tok, resolve(tok, comp) if link else None))
        pos = m.end()
    out.append(textmath(s[pos:], q))
    return "".join(out)


MD_TOKEN = re.compile(r"(\$[^$]+\$|`[^`]+`|\*\*[^*]+\*\*|\*[^*\s][^*]*\*)")


def md(s: str, comp: str | None = None) -> str:
    """Markdown with $...$ math (kept), `code` (linked when the name is pinned), *emphasis*."""
    q = Quotes()
    out = []
    for part in MD_TOKEN.split(s):
        if not part:
            continue
        if part.startswith("$"):
            out.append(part)
        elif part.startswith("`"):
            name = part[1:-1]
            out.append(code(name, resolve(name, comp)))
        elif part.startswith("**"):
            out.append(r"\textbf{%s}" % md(part[2:-2], comp))
        elif part.startswith("*"):
            out.append(r"\emph{%s}" % md(part[1:-1], comp))
        else:
            out.append(textmath(part, q))
    return "".join(out)


def caption_text(s: str) -> str:
    """SVG descriptions are ASCII pseudo-math; make them read like mathematics."""
    s = s.replace("<=", "≤").replace(">=", "≥").replace("->", "→").replace("!=", "≠").replace("+-", "±")
    words = {"pi": "π", "gamma": "γ", "theta": "θ", "delta": "δ", "delta1": "δ₁", "eps": "ε",
             "epsilon": "ε", "rho": "ρ", "beta": "β", "sigma": "σ", "eta": "η", "Lambda": "Λ",
             "Phi": "Φ", "chi": "χ", "psi": "ψ", "lambda": "λ", "mu": "μ"}
    s = re.sub(r"(?<![A-Za-z])(\d*)(pi|gamma|theta|delta1|delta|epsilon|eps|rho|beta|sigma|eta|Lambda|Phi|chi|psi|lambda|mu)(?![A-Za-z])(?! lift| correspondence| chain| series)",
               lambda m: m.group(1) + words[m.group(2)], s)
    s = s.replace(" - ", " − ").replace("(-", "(−")
    return ptex(s)


# ----------------------------------------------------------------------------- link resolution
INDEX: dict[str, set[str]] = {}
LOCAL: dict[str, dict[str, str]] = {}


def _add(index: dict, key: str, url: str) -> None:
    index.setdefault(key, set()).add(url)


def ident_tokens(name: str) -> list[str]:
    return [t for t in re.split(r"[\s()/·,]+", name) if t and re.search(r"[A-Za-z]", t)]


def build_index() -> None:
    for n in MODEL["nodes"]:
        d, u = n["declaration"], n["url"]
        if d and u:
            parts = d.split(".")
            for k in range(len(parts)):
                _add(INDEX, ".".join(parts[k:]), u)
    for c in MODEL["components"]:
        loc: dict[str, set[str]] = {}
        for entry in c["lean"]:
            for tok in ident_tokens(entry["name"]):
                parts = tok.split(".")
                for k in range(len(parts)):
                    _add(loc, ".".join(parts[k:]), entry["url"])
        LOCAL[c["id"]] = {k: next(iter(v)) for k, v in loc.items() if len(v) == 1}


def resolve(name: str, comp: str | None = None) -> str | None:
    """Pinned URL for a Lean name, or None when it is unknown or ambiguous. Order: a unique node
    declaration (full name or dotted suffix), the component's own Lean entries, then a unique match
    among all components' entries."""
    key = name.split(" ")[0]
    urls = INDEX.get(key)
    if urls and len(urls) == 1:
        return next(iter(urls))
    if comp and key in LOCAL.get(comp, {}):
        return LOCAL[comp][key]
    if not urls:
        hits = {loc[key] for loc in LOCAL.values() if key in loc}
        if len(hits) == 1:
            return next(iter(hits))
    return None


def src_location(url: str) -> str:
    """'ClaimStrip.lean, L42–57' from a pinned URL (the full path is in the link)."""
    path, _, frag = url.partition("#")
    mathlib = "mathlib4" in path
    tail = path.split("/src/")[-1] if "/src/" in path else path.split("/Mathlib/")[-1]
    segs = tail.split("/")
    short = segs[-1]
    lines = ""
    m = re.fullmatch(r"L(\d+)-L(\d+)", frag or "")
    if m:
        a, b = m.groups()
        lines = f"L{a}" if a == b else f"L{a}–{b}"
    s = short + (", " + lines if lines else "")
    return s + (" (Mathlib)" if mathlib else "")


# ----------------------------------------------------------------------------- statements
def split_top(s: str, sep: str = r"\qquad") -> list[str]:
    parts, depth, i, start = [], 0, 0, 0
    while i < len(s):
        c = s[i]
        if c == "\\":
            if depth == 0 and s.startswith(sep, i) and not s[i + len(sep): i + len(sep) + 1].isalpha():
                parts.append(s[start:i])
                i += len(sep)
                start = i
                continue
            j = i + 1
            if j < len(s) and s[j].isalpha():
                while j < len(s) and s[j].isalpha():
                    j += 1
            else:
                j += 1
            i = j
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        i += 1
    parts.append(s[start:])
    return [p.strip() for p in parts if p.strip()]


def display(stmt: str) -> str:
    lines = split_top(stmt)
    if len(lines) == 1:
        return r"\bpdisplay{%s}" % lines[0]
    return "\\bpdisplay{\\begin{gathered}\n" + " \\\\\n".join(lines) + "\n\\end{gathered}}"


