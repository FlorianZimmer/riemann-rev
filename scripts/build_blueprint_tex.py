def kicker_tex(c: dict) -> str:
    segs = [s.strip() for s in c["kicker"].split("·")]
    out = []
    for s in segs:
        url = None
        if s.endswith(".lean"):
            for e in c["lean"]:
                if e["url"].split("#")[0].endswith("/" + s):
                    url = e["url"].split("#")[0]
                    break
        else:
            head = s.split(" ")[0]
            url = LOCAL[c["id"]].get(head) or resolve(head, c["id"])
            if url is None:
                for e in c["lean"]:
                    if head in ident_tokens(e["name"]) or e["name"].split(" (")[0].endswith("." + head):
                        url = e["url"]
                        break
        if url:
            out.append(r"\href{%s}{\bpcode{%s}}" % (url_tex(url), code_inner(s)))
        else:
            out.append(r"\bpkickertext{%s}" % textmath(s))
    return r"\bpkickersep ".join(out)


